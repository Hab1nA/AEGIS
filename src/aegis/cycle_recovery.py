"""Cycle-failure repair wiring over the replay-safe RecoverySupervisor.

When one v2 cycle bricks, the control plane asks the Prosecutor model for a
patch, publishes the isolated recovery candidate through the journaled Git
connector, validates it, and activates the repaired role version.  Every step
is persisted to the same EventStore with intent-first receipts so a crash at
any point resumes rather than repeats.
"""

from __future__ import annotations

